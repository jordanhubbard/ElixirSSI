import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

export async function checkWorkspaceFeatures({page, port, prefix, output, rpc, nav, result, evaluate}) {
  const base = `http://localhost:${port}`;
  const target = 'host.docker.internal|2321';
  const project = 'project:acceptance_app';
  const cluster = `cluster:${target}`;
  const nodes = `node:${target}`;
  const idle = () => page.waitForFunction(() => !document.querySelector('.file-controls')?.disabled, null, {timeout:120000});
  const pane = () => page.locator('.file-pane.active-pane');
  const tool = async name => {
    const selectors = {create:'#create-entry', upload:'#upload-files', rename:'#rename-file', projects:'#import-project', links:'#link-folder', sync:'#preview-sync'};
    if (!await page.locator(selectors[name]).isVisible()) await page.locator(`button[phx-click=tool][phx-value-name=${name}]`).click();
  };
  const browsePane = async (side, space, directory='') => {
    await idle();
    const form=page.locator(`#location-${side}`);
    const current=new URL(page.url()).searchParams;
    if(current.get(side)===space && current.get(side+'_path')===directory) return;
    await form.locator('[name=space]').selectOption(space);
    await form.locator('[name=path]').fill(directory);
    await form.getByRole('button',{name:'Open',exact:true}).click();
    await page.waitForFunction(({side,space,directory}) => {
      const q=new URLSearchParams(location.search); return q.get(side)===space && q.get(side+'_path')===directory;
    },{side,space,directory});
    await idle();
  };
  const open = async (space, directory = '') => {
    await page.goto(`${base}/files?${new URLSearchParams({space, path:directory})}`);
    await page.waitForSelector('.phx-connected'); await idle();
  };
  const notice = text => page.locator('.notice[role=status]').filter({hasText:text}).waitFor({timeout:120000});
  const create = async (name, kind='file') => {
    await tool('create');
    await page.locator('#create-entry [name=name]').fill(name);
    await page.locator('#create-entry [name=kind]').selectOption(kind);
    await page.locator('#create-entry button').click();
    await pane().locator('.file-list').getByRole('button',{name:kind === 'folder' ? `Folder · ${name}` : name,exact:true}).waitFor({timeout:60000});
  };
  const download = async locator => {
    const event = page.waitForEvent('download'); await locator.click();
    const item = await event; const chunks=[];
    for await (const chunk of await item.createReadStream()) chunks.push(chunk);
    return Buffer.concat(chunks);
  };
  const openFile = async name => {
    await idle();
    await pane().locator('.file-list').getByRole('button',{name,exact:true}).click();
    await page.getByRole('button',{name:'Edit',exact:true}).click();
    await page.waitForFunction(name => Array.from(document.querySelectorAll('h2')).some(h => h.textContent.trim() === name || h.textContent.trim().endsWith('/'+name)), name, {timeout:60000});
  };
  const save = async source => {
    await page.locator('#file-editor textarea').fill(source);
    await page.locator('#file-editor button').click(); await notice('File saved.');
  };
  const copy = async (space, destination) => {
    const sourceSide=(await pane().getAttribute('id')).replace('pane-','');
    const destinationSide=sourceSide==='left'?'right':'left';
    const sourceLocation=await page.locator(`#location-${sourceSide} [name=space]`).inputValue();
    const sourceDirectory=await page.locator(`#location-${sourceSide} [name=path]`).inputValue();
    await browsePane(destinationSide,space,path.posix.dirname(destination)==='.'?'':path.posix.dirname(destination));
    assert.equal(await page.locator(`#location-${sourceSide} [name=space]`).inputValue(),sourceLocation);
    assert.equal(await page.locator(`#location-${sourceSide} [name=path]`).inputValue(),sourceDirectory);
    await page.locator(`#copy-${destinationSide}`).click();
    await page.locator('#copy-preview').waitFor({timeout:60000});
    assert((await page.locator('#copy-preview').innerText()).includes(destination));
    await page.locator('#copy-preview button[phx-click=apply-copy]').click();
    await notice('Copied'); await idle();
    await page.locator(`#pane-${destinationSide} button[phx-click=pane-select]`).filter({hasText:path.posix.basename(destination)}).waitFor();
  };
  const syncPreview = async (space, directory) => {
    await browsePane('right',space,directory);
    await tool('sync');
    await page.locator('#preview-sync').click();
    await page.locator('#sync-preview').waitFor({timeout:120000});
    assert((await page.locator('#sync-preview').innerText()).includes(`Right: ${space}/${directory}`));
  };
  const syncApply = async expected => {
    await page.locator('#sync-preview button[phx-click=apply-sync]').click();
    await page.locator('#sync-preview').waitFor({state:'detached',timeout:120000});
    await notice(expected || 'Both folders agree');
    await page.waitForFunction(() => !document.querySelector('.file-controls')?.disabled, null, {timeout:120000});
  };
  const bytes = Buffer.alloc(300123); for (let i=0;i<bytes.length;i++) bytes[i]=i%256;
  await open(project); await create('assets','folder'); await open(project,'assets');
  await tool('upload');
  await page.locator('#upload-files input[type=file]').setInputFiles({name:'binary.dat',mimeType:'application/octet-stream',buffer:bytes});
  await page.locator('#upload-files button[type=submit], #upload-files button:not([type])').last().click();
  await notice('binary.dat: Done.');
  const row = pane().locator('.file-list').locator('li').filter({hasText:'binary.dat'});
  await row.getByRole('button',{name:'binary.dat',exact:true}).click();
  assert.deepEqual(await download(page.getByRole('link',{name:'Download file',exact:true})),bytes);
  await create('note.txt'); await openFile('note.txt'); await save('browser text');
  rpc('File.write!(Path.join([ElixirSSI.Command.Projects.root(), "acceptance_app", "assets/note.txt"]), "external edit")');
  await page.locator('#file-editor textarea').fill('stale edit'); await page.locator('#file-editor button').click();
  await notice('Destination changed');
  assert.equal(fs.readFileSync(path.join(prefix,'state/command/projects/acceptance_app/assets/note.txt'),'utf8'),'external edit');
  await tool('rename'); await page.locator('#rename-file [name=to]').fill('renamed.txt');
  await page.locator('#rename-file button').click();
  await openFile('renamed.txt'); await page.getByRole('button',{name:'Delete file',exact:true}).click();
  await notice('Done.');
  assert(!fs.existsSync(path.join(prefix,'state/command/projects/acceptance_app/assets/renamed.txt')));
  await open(project);
  await tool('projects');
  const archive=await download(page.getByRole('link',{name:'Download project ZIP',exact:true}));
  await page.locator('#import-project [name=name]').fill('imported_workspace');
  await page.locator('#import-project input[type=file]').setInputFiles({name:'project.zip',mimeType:'application/zip',buffer:archive});
  await page.locator('#import-project').getByRole('button',{name:'Import project',exact:true}).click();
  await page.waitForURL('**space=project%3Aimported_workspace**');
  assert.deepEqual(fs.readFileSync(path.join(prefix,'state/command/projects/imported_workspace/assets/binary.dat')),bytes);
  console.log('PASS: browser binary upload/download, editing, stale-save rejection, rename/delete and project ZIP round trip');

  await open(cluster); await create('workspace_acceptance','folder');
  await open(project,'assets'); await openFile('binary.dat'); await copy(cluster,'workspace_acceptance/binary.dat');
  await open(cluster,'workspace_acceptance');
  await pane().getByRole('button',{name:'binary.dat',exact:true}).click();
  assert.deepEqual(await download(page.getByRole('link',{name:'Download file',exact:true})),bytes);
  await open(nodes);
  const nodeName=await pane().locator('.file-list').getByRole('button',{name:/^Folder · /}).first().getAttribute('phx-value-path');
  await open(nodes,`${nodeName}/data`); await create('workspace_acceptance','folder');
  await open(cluster,'workspace_acceptance'); await openFile('binary.dat'); await copy(nodes,`${nodeName}/data/workspace_acceptance/binary.dat`);
  await open(nodes,`${nodeName}/data/workspace_acceptance`);
  await pane().getByRole('button',{name:'binary.dat',exact:true}).click();
  assert.deepEqual(await download(page.getByRole('link',{name:'Download file',exact:true})),bytes);
  await openFile('binary.dat'); await copy(project,'assets/binary.dat');
  assert.deepEqual(fs.readFileSync(path.join(prefix,'state/command/projects/acceptance_app/assets/binary.dat')),bytes);
  await page.screenshot({path:path.join(output,'installed-files-desktop.png'),fullPage:true});
  console.log('PASS: checksummed multi-chunk copies and downloads across command, cluster and node-local files');

  const linked=path.join(prefix,'linked folder'); fs.mkdirSync(linked,{mode:0o700}); fs.writeFileSync(path.join(linked,'note.txt'),'baseline');
  await tool('links');
  await page.locator('#link-folder [name=name]').fill('Acceptance host folder');
  await page.locator('#link-folder [name=path]').fill(linked);
  await page.locator('#link-folder [name=writable]').selectOption('true');
  await page.locator('#link-folder button').click();
  await page.waitForURL('**space=link%3A**',{timeout:120000});
  await pane().locator('.file-list').getByRole('button',{name:'note.txt',exact:true}).waitFor({timeout:60000});
  const linkSpace=await pane().locator('[name=space]').inputValue();
  await open(cluster,'workspace_acceptance'); await create('synced','folder');
  await open(linkSpace); await syncPreview(cluster,'workspace_acceptance/synced'); await syncApply();
  console.log('PASS: host-folder initial synchronization');
  fs.writeFileSync(path.join(linked,'note.txt'),'host edit');
  await open(cluster,'workspace_acceptance/synced'); await openFile('note.txt'); await save('cluster edit');
  await open(linkSpace); await syncPreview(cluster,'workspace_acceptance/synced');
  await page.locator('#resolve-sync select').selectOption('left'); await page.locator('#resolve-sync button').click();
  await syncApply();
  await open(cluster,'workspace_acceptance/synced'); await openFile('note.txt');
  assert.equal(await page.locator('#file-editor textarea').inputValue(),'host edit');
  await open(linkSpace); await syncPreview(cluster,'workspace_acceptance/synced');
  fs.writeFileSync(path.join(linked,'note.txt'),'changed after preview');
  await syncApply('changed');
  console.log('PASS: host-folder conflict resolution and stale-plan rejection');
  await syncPreview(cluster,'workspace_acceptance/synced'); await syncApply();
  fs.unlinkSync(path.join(linked,'note.txt'));
  await syncPreview(cluster,'workspace_acceptance/synced');
  assert.match(await page.locator('#sync-preview').innerText(),/Delete.*note.txt/);
  await syncApply();
  await open(cluster,'workspace_acceptance/synced');
  assert.equal(await pane().locator('.file-list').locator('li').count(),0);
  await create('from_cluster.txt'); await openFile('from_cluster.txt'); await save('copied back to host');
  await open(linkSpace); await syncPreview(cluster,'workspace_acceptance/synced'); await syncApply();
  assert.equal(fs.readFileSync(path.join(linked,'from_cluster.txt'),'utf8'),'copied back to host');
  await open(linkSpace); await page.reload(); await page.waitForSelector('.phx-connected');
  await idle(); await tool('sync');
  await page.getByText('Previous folder pairs',{exact:true}).click();
  await page.getByRole('button',{name:'Compare again',exact:true}).waitFor({timeout:60000});
  const readonly=path.join(prefix,'readonly folder'); fs.mkdirSync(readonly); fs.writeFileSync(path.join(readonly,'original.txt'),'preserved');
  await tool('links');
  await page.locator('#link-folder [name=name]').fill('Acceptance read-only folder');
  await page.locator('#link-folder [name=path]').fill(readonly);
  await page.locator('#link-folder [name=writable]').selectOption('false');
  await page.locator('#link-folder button').click();
  await page.waitForURL(url => url.searchParams.get('space')?.startsWith('link:') && url.searchParams.get('space') !== linkSpace, {timeout:120000});
  await pane().locator('.file-list').getByRole('button',{name:'original.txt',exact:true}).waitFor({timeout:60000});
  await tool('create');
  await page.locator('#create-entry [name=name]').fill('forbidden.txt'); await page.locator('#create-entry button').click();
  await notice('read-only'); assert(!fs.existsSync(path.join(readonly,'forbidden.txt')));
  await tool('links');
  await page.locator('li').filter({hasText:'Acceptance read-only folder'}).getByRole('button',{name:'Unlink',exact:true}).click();
  await page.waitForURL(`${base}/files`);
  await idle();
  assert.equal(await page.locator('#pane-left .pane-error').count(),0);
  assert(!(await page.locator('#location-left [name=space]').inputValue()).startsWith('link:'));
  assert.equal(fs.readFileSync(path.join(readonly,'original.txt'),'utf8'),'preserved');
  console.log('PASS: linked host folder, bidirectional sync conflicts, stale-plan rejection, deletion and persisted baseline');

  await page.goto(`${base}/`); await page.waitForSelector('.phx-connected');
  await nav('Projects'); await page.getByRole('button',{name:'Demos',exact:true}).click();
  await page.locator('#demos-project .member').filter({hasText:'Mandelbrot'}).getByRole('link',{name:'Open source',exact:true}).click();
  assert.equal(new URL(page.url()).searchParams.get('project'),'Demos');
  await page.locator('#demo-source').waitFor({timeout:60000});
  assert.equal(await page.locator('#demos-project .member').count(),4);
  assert.equal(await page.getByRole('link',{name:'Demo sources',exact:true}).count(),0);
  await page.getByText('Source identity',{exact:true}).click();
  assert.match(await page.locator('#demo-source').innerText(),/Source SHA-256/);
  await page.locator('#copy-demo [name=name]').fill('acceptance_mandelbrot');
  await page.locator('#copy-demo button').click(); await page.waitForURL('**project=acceptance_mandelbrot');
  await page.waitForSelector('.phx-connected');
  const source=await page.locator('#source-editor textarea').inputValue();
  assert.match(source,/defmodule AcceptanceMandelbrot.App/);
  await page.locator('#source-editor textarea').fill(source.replace('Mandelbrot - computed by the cluster','My edited Mandelbrot'));
  await page.locator('#source-editor button').click();
  await page.getByRole('button',{name:'Test',exact:true}).click(); await result('acceptance_mandelbrot: test');
  await nav('Projects'); await page.getByRole('button',{name:'acceptance_mandelbrot',exact:true}).click();
  await page.locator('#deploy-demo button').click(); await result('Deploy and run desktop app acceptance_mandelbrot');
  const proof=await evaluate('Enum.reduce_while(1..80, nil, fn _, _ -> s = SSI.Desktop.app_state(AcceptanceMandelbrot.App); if s && map_size(s.tiles) == 96 && s.elapsed, do: {:halt, :ok}, else: (Process.sleep(250); {:cont, nil}) end); rendered = SSI.Desktop.app_state(AcceptanceMandelbrot.App); unless rendered && map_size(rendered.tiles) == 96 && map_size(rendered.nodes) >= 2, do: raise("edited demo did not render across cluster nodes"); st = :sys.get_state(SSI.Service.whereis(:desktop)); win = Enum.find(st.windows, &(&1.app == AcceptanceMandelbrot.App)); unless win && AcceptanceMandelbrot.App.title() == "My edited Mandelbrot", do: raise("edited demo did not launch"); handles = Enum.flat_map(st.windows, &Map.get(&1, :tiles, [])); unless length(handles) == length(Enum.uniq(handles)), do: raise("desktop windows share pixel surfaces"); for n <- SSI.Cluster.members(), do: true = :erpc.call(n, Code, :ensure_loaded?, [AcceptanceMandelbrot.Mandelbrot]); :edited_demo_verified');
  assert.match(proof,/edited_demo_verified/);
  await evaluate(':persistent_term.put(:acceptance_desktop_pid, SSI.Service.whereis(:desktop)); :desktop_recorded');
  await nav('Projects'); await page.getByRole('button',{name:'acceptance_mandelbrot',exact:true}).click();
  const edited = await page.locator('#source-editor textarea').inputValue();
  await page.locator('#source-editor textarea').fill(edited.replace('My edited Mandelbrot', 'My revised Mandelbrot'));
  await page.locator('#source-editor button').click();
  await page.getByText(/Saved .*mandelbrot_app.ex\./).waitFor();
  await page.locator('#deploy-demo button').click(); await result('Deploy and run desktop app acceptance_mandelbrot');
  assert.match(await evaluate('ready = Enum.reduce_while(1..80, false, fn _, _ -> st = :sys.get_state(SSI.Service.whereis(:desktop)); win = Enum.find(st.windows, &(&1.app == AcceptanceMandelbrot.App)); if win && map_size(win.state.tiles) == 96 && win.state.pending == [] && map_size(st.upload_queue) == 0, do: {:halt, true}, else: (Process.sleep(250); {:cont, false}) end); unless ready and AcceptanceMandelbrot.App.title() == "My revised Mandelbrot" and SSI.Service.whereis(:desktop) == :persistent_term.get(:acceptance_desktop_pid), do: raise("redeployment interrupted the desktop or did not render"); :redeploy_verified'), /redeploy_verified/);
  await nav('Desktop'); await page.screenshot({path:path.join(output,'installed-demo-source-workflow.png'),fullPage:true});
  for (const id of ['cluster','processes','shell']) {
    await page.goto(`${base}/?${new URLSearchParams({project:'Demos',target,id})}`); await page.waitForSelector('.phx-connected');
    await page.locator('#demo-source').waitFor({timeout:60000});
    const name=`acceptance_${id}_demo`;
    await page.locator('#copy-demo [name=name]').fill(name); await page.locator('#copy-demo button').click();
    await page.waitForURL(`**project=${name}`); await page.waitForSelector('.phx-connected');
    await page.getByRole('button',{name:'Test',exact:true}).click(); await result(`${name}: test`);
    await nav('Projects'); await page.getByRole('button',{name,exact:true}).click();
    await page.locator('#deploy-demo button').click(); await result(`Deploy and run desktop app ${name}`);
    const module = `Acceptance${id[0].toUpperCase()+id.slice(1)}Demo.App`;
    assert.match(await evaluate(`unless SSI.Desktop.app_state(${module}) && SSI.Service.whereis(:desktop) == :persistent_term.get(:acceptance_desktop_pid), do: raise("copied demo did not launch or interrupted the desktop"); :copied_demo_verified`),/copied_demo_verified/);
  }
  console.log('PASS: all guest demo sources copied, tested and launched; edited distributed Mandelbrot deployed and launched with independent surfaces');
  await page.goto(`${base}/files?${new URLSearchParams({space:linkSpace})}`); await page.waitForSelector('.phx-connected');
  await idle();
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw new Error('Files page mobile overflow');
  await page.screenshot({path:path.join(output,'installed-files-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(`${base}/`); await page.waitForSelector('.phx-connected');
  return {linkSpace,target,cluster,nodes,nodeName,linked};
}
